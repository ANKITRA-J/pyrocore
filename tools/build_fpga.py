#!/usr/bin/env python3
"""Build the real PyroCore FPGA design with Renesas tools; never upload."""
from pathlib import Path
import argparse,base64,csv,hashlib,importlib.util,json,os,re,struct,subprocess,sys,zlib
import xml.etree.ElementTree as ET
ROOT=Path(__file__).resolve().parents[1]
PROJECT=ROOT/'fpga/project'
BUILD=ROOT/'build/fpga'
MODULES=['pyrocore_top','pyrocore_core','particle_renderer','frame_streamer','uart_rx','uart_tx']

def external_default():
    if os.environ.get('GOCONFIGURE_EXTERNAL'):return Path(os.environ['GOCONFIGURE_EXTERNAL'])
    if sys.platform=='darwin':return Path('/Applications/Go Configure Software Hub.app/Contents/MacOS/external')
    return Path('/opt/go-configure-sw-hub/bin/external')

def write_changed(p,text):
    p.parent.mkdir(parents=True,exist_ok=True)
    if not p.exists() or p.read_text()!=text:p.write_text(text)

def prepare():
    BUILD.mkdir(parents=True,exist_ok=True)
    source='// Generated by tools/build_fpga.py from fpga/rtl. Edit those source files.\n'
    source+='\n'.join((ROOT/'fpga/rtl'/f'{m}.v').read_text() for m in MODULES)
    write_changed(PROJECT/'ffpga/src/main.v',source)
    rows=list(csv.DictReader((PROJECT/'pins.csv').open(),delimiter=';'))
    extra={'GPIO5_IN [PIN 18]':'uart_rx_pin','GPIO6_OUT [PIN 19]':'uart_tx_pin','GPIO6_OE [PIN 19]':'uart_tx_oe'}
    blocks={};clock=[];records=[]
    for row in rows:
        function=row['FUNCTION'];signal=extra.get(function,row['PORT']);row['PORT']=signal
        position=row['POSITION']
        if position.startswith('CLK'):
            side,direction,index=re.search(r'clk_side=(\w) (Input|Output)(\d+)',position).groups()
            identity=f'CLK_t[0:0]_{side}_{"in" if direction=="Input" else "out"}{index}'
            if signal:clock.extend([f'EFLX_CLK chip_tile_x=0, chip_tile_y=0, clk_side={side}',f'    {direction}={index}, pin={signal}'])
        else:
            x,y,direction,index=re.search(r'coord\[(\d+), (\d+)\] (Input|Output)(\d+)',position).groups()
            identity=f'IOB_t[0:0]_xy[{x}:{y}]_{"in" if direction=="Input" else "out"}{index}'
            blocks.setdefault((x,y),[])
            if signal:blocks[(x,y)].append(f'    {direction}={index}, pin={signal}, '+('output_delay=-1' if direction=='Output' else 'input_delay=-1'))
        if signal:records.append((identity,signal))
    lines=clock[:]
    for (x,y),signals in blocks.items():lines.extend([f'EFLX_IOB chip_tile_x=0, chip_tile_y=0, chip_x={x}, chip_y={y}',*signals])
    write_changed(BUILD/'io_spec_in.txt','\n'.join(lines)+'\n')
    (BUILD/'floorplanspec.fp').write_bytes(b'1K\n\nM\n')
    # Retain device/clock/pin properties from the known-good dedicated BRAM project.
    tree=ET.parse(PROJECT/'pyrocore.ffpga');root=tree.getroot()
    rec=root.find('fpga-data/io-spec-tool/records');rec.clear();rec.set('filter','16')
    for identity,signal in records:
        ET.SubElement(ET.SubElement(rec,'record',id=identity),'port-name').text=signal
    root.set('projectChecksumState','0');root.set('projectChecksum','00000000')
    for state in root.findall('fpga-data/pipelineStagesStates/pipelineStageState/pipelineState'):state.text='0'
    ET.indent(tree,space='    ')
    xml=ET.tostring(root,encoding='unicode')
    write_changed(PROJECT/'pyrocore.ffpga','<?xml version="1.0" encoding="UTF-8"?>\n'+xml+'\n')
    # Keep the exported table aligned for inspection and GUI use.
    import io
    f=io.StringIO();w=csv.DictWriter(f,fieldnames=['POSITION','FUNCTION','PORT'],delimiter=';');w.writeheader();w.writerows(rows)
    write_changed(PROJECT/'pins.csv',f.getvalue())

def run(command,cwd,log,env=None):
    print(f'Running {Path(str(command[0])).name}; log {log.relative_to(ROOT)}',flush=True)
    with log.open('w') as f:r=subprocess.run([str(a) for a in command],cwd=cwd,env=env,stdout=f,stderr=subprocess.STDOUT)
    if r.returncode:
        print(log.read_text(errors='replace')[-7000:]);raise SystemExit(r.returncode)

def synth(external):
    source=PROJECT/'ffpga/src/main.v'
    script=f'''read_verilog -sv "{source}"
hierarchy -check -top pyrocore_top
flatten -noscopeinfo
synth_xilinx -top pyrocore_top -nobram -noiopad -nodsp -abc9 -nocarry -nowidelut
clean
autoname
write_verilog post_synth_results.v
write_edif netlist.edif
tee -q -o synthesis_report.txt stat
'''
    (BUILD/'synth.ys').write_text(script)
    run([external/'yosys/v59/yosys','-Q','-T','-s','synth.ys'],BUILD,BUILD/'synthesis.log')
    print((BUILD/'synthesis_report.txt').read_text())

def blob(arguments):
    parts=[str(x).encode() for x in arguments]
    raw=struct.pack('>I',len(parts))+b''.join(struct.pack('>I',len(p)) for p in parts)+b''.join(parts)
    return base64.b64encode(struct.pack('>I',len(raw))+zlib.compress(raw)).decode()

def pnr(external,cpus):
    out=BUILD/'pnr';out.mkdir(exist_ok=True)
    args=['-edif',BUILD/'netlist.edif','-fp',BUILD/'floorplanspec.fp',
          '-ENABLE_BITSTREAM_OUTPUT_AXI','1','-ENABLE_BITSTREAM_OUTPUT_AXI_CRC','0',
          '-ENABLE_HIGH_DENSITY_PACKING','1','-ENABLE_HIGH_DENSITY_IO_PACKING','0',
          '-CLK_CONCURRENT_OPT','1','-PLACE_AND_TRIAL_ROUTE','0','-PNR_TRIAL_ITER_TOTAL','20',
          '-MAX_ROUTE_ITER','300','-MAX_CPU',str(cpus),'-TIMING_ANALYSIS_CORNER','0',
          '-TIMING_DRIVEN_PACKING_THR','0.70','-io',BUILD/'io_spec_in.txt',
          '-sdc',PROJECT/'ffpga/timing-constraints/clocks.sdc']
    (out/'arguments.json').write_text(json.dumps([str(a) for a in args],indent=2)+'\n')
    env=dict(os.environ,EFLX_COMPILER_INSTALL=str(external/'eda-placer/v23'))
    run([external/'eda-placer/v23/eda-placer','FPGA_DATA',blob(args),'0'],out,out/'placer.log',env)
    if not (out/'EFLX_bitstream_AXI.log').exists():raise SystemExit('No AXI bitstream generated; inspect placer.log')
    print((out/'PNR_RESOURCE.log').read_text()[:3500])
    print((out/'PNR_TIMING.log').read_text()[:1600])

def package():
    vendor=ROOT/'tools/vendor/gen_bitstreams.py'
    spec=importlib.util.spec_from_file_location('bitstream_format',vendor);mod=importlib.util.module_from_spec(spec);spec.loader.exec_module(mod)
    axi=mod.read_axi(BUILD/'pnr/EFLX_bitstream_AXI.log')
    if len(axi)!=11264:raise SystemExit('Unexpected AXI length; refusing incomplete bitstream')
    words=[0]*mod.MCU_PREAMBLE_LEN+mod.FMEM_HEADER+[mod.bswap32(x) for x in axi]+[0]*mod.MCU_TRAILER_LEN
    binary=struct.pack(f'>{len(words)}I',*words)
    image=BUILD/'FPGA_bitstream_MCU.bin';image.write_bytes(binary)
    metadata={'target':'SLG47910V Rev BB','format':'MCU SPI','bytes':len(binary),
      'sha256':hashlib.sha256(binary).hexdigest(),'physical_board_tested':False,
      'sources':{str((ROOT/'fpga/rtl'/f'{m}.v').relative_to(ROOT)):hashlib.sha256((ROOT/'fpga/rtl'/f'{m}.v').read_bytes()).hexdigest() for m in MODULES}}
    (BUILD/'manifest.json').write_text(json.dumps(metadata,indent=2)+'\n')
    print(f'Built {image.relative_to(ROOT)} ({len(binary)} bytes); no device upload')

def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('step',nargs='?',default='all',choices=['prepare','synth','pnr','package','all'])
    ap.add_argument('--external',type=Path,default=external_default())
    ap.add_argument('--cpus',type=int,default=4)
    a=ap.parse_args();prepare();external=a.external.resolve()
    if a.step in ('synth','all'):synth(external)
    if a.step in ('pnr','all'):pnr(external,a.cpus)
    if a.step in ('package','all'):package()
if __name__=='__main__':main()
