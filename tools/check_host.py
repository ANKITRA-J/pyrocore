#!/usr/bin/env python3
"""Check host decoders; optionally pass an RTL-produced UART packet end to end."""
from pathlib import Path
import argparse,base64,json,subprocess,sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from desktop.protocol import decode_message

def run(args):subprocess.run([str(a) for a in args],cwd=ROOT,check=True)
def main():
    ap=argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--packet',type=Path,help='1545-byte frame captured by the RTL testbench')
    a=ap.parse_args()
    run([sys.executable,'-m','unittest','discover','-s','tests','-v'])
    build=ROOT/'build/host';build.mkdir(parents=True,exist_ok=True)
    exe=build/'frame-parser'
    run(['c++','-std=c++17','-O2',ROOT/'firmware/pyrocore/tests/test_frame_parser.cpp','-o',exe])
    run([exe])
    if a.packet:
        p=a.packet.resolve();run([exe,p]);packet=p.read_bytes()
        if len(packet)!=1545 or packet[:4]!=b'PY\x01F' or packet[6:8]!=b'\x00\x06':
            raise SystemExit('Unexpected RTL frame header or size')
        # Same USB JSON envelope generated by the firmware after native CRC acceptance.
        envelope={'type':'frame','seq':int.from_bytes(packet[4:6],'little'),
          'width':64,'height':64,'format':'indexed3-lsb','source':'fpga',
          'crc_ok':True,'data':base64.b64encode(packet[8:-1]).decode()}
        image=decode_message(json.dumps(envelope))
        (build/'rtl_usb_frame.json').write_text(json.dumps(envelope)+'\n')
        lit=sum(bool(c) for c in image['pixels'])
        colours=sorted(set(image['pixels'])-{0})
        print(f'PASS: RTL UART packet → exact firmware parser → desktop decoder;4096 pixels, {lit} lit, colours={colours}')
if __name__=='__main__':main()
